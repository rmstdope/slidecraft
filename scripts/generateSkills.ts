/**
 * Generates the skills' component catalogue (UX overhaul U4) from the component registry, so the
 * skills can never drift from the components. `bun run skills` writes it; `bun run build` runs it;
 * tests/skills.test.ts fails when the committed file is out of date.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { getAllTemplates, getParts, getTopLevelComponents } from '../src/components/slides/defineComponent.ts'
import '../src/components/slides/index.ts'
import { COMPONENT_CATEGORIES } from '../server/lib/agentContext.ts'

const ROOT = join(import.meta.dir, '..')
export const CATALOGUE_FILE = join(ROOT, 'skills', 'slidecraft-presentations', 'references', 'components.md')
export const API_FILE = join(ROOT, 'skills', 'slidecraft-components', 'references', 'slidecraft-api.md')
const API_INDEX = join(ROOT, 'src', 'vault-api', 'index.ts')

import { catalogueEntry as entry } from '../server/lib/catalogue.ts'
import { readFileSync } from 'node:fs'

export function buildCatalogue(): string {
  const all = getTopLevelComponents().map((c) => c.registry)
  const byName = new Map(all.map((r) => [r.name, r]))
  const known = new Set(Object.values(COMPONENT_CATEGORIES).flat())
  const groups: [string, string[]][] = [...Object.entries(COMPONENT_CATEGORIES), ['Other', all.map((r) => r.name).filter((n) => !known.has(n))]]
  const out = [
    '<!-- Generated from the component registry by scripts/generateSkills.ts (`bun run skills`). Do not edit. -->',
    '',
    '# Components',
    '',
    'Every slide component, grouped by family, with its props and the smallest useful usage. Import',
    'each one you use from `@components`. Parts (such as `ListItem`) are listed under their parent.',
    '',
  ]
  out.push('| Family | Components |', '|---|---|')
  for (const [group, names] of groups) {
    const present = names.filter((n) => byName.has(n))
    if (present.length) out.push(`| ${group} | ${present.map((n) => `\`${n}\``).join(', ')} |`)
  }
  for (const [group, names] of groups) {
    const present = names.filter((n) => byName.has(n))
    if (!present.length) continue
    out.push('', `## ${group}`)
    for (const name of present) {
      out.push('', ...entry(byName.get(name)!, '###'))
      for (const part of getParts(name)) out.push('', ...entry(part.registry, '####'))
    }
  }
  out.push('', '## Slide templates', '', 'Whole-slide starting points (the editor\'s "Add slide" offers them too).')
  for (const t of getAllTemplates()) out.push('', `### ${t.name}`, '', t.description, '', '```mdx', t.snippet, '```')
  return `${out.join('\n')}\n`
}

/**
 * What vault code can import from 'slidecraft' (vault components plan, V4), grouped as
 * src/vault-api/index.ts groups it. The groups and names come from that file and the modules it
 * re-exports, so the reference follows the module.
 */
export async function buildApiReference(): Promise<string> {
  const source = readFileSync(API_INDEX, 'utf8')
  const api = (await import('../src/vault-api/index.ts')) as Record<string, unknown>
  const components = new Map(getTopLevelComponents(null).map((c) => [c.registry.name, c.registry]))
  const parts = new Set(getTopLevelComponents(null).flatMap((c) => getParts(c.registry.name, null).map((p) => p.registry.name)))
  const out = [
    '<!-- Generated by `bun run skills` from src/vault-api/index.ts. Do not edit. -->',
    '# The `slidecraft` module',
    '',
    `What a vault component may import from \`slidecraft\` (API version ${String(api.API_VERSION)}). Besides it, vault code may import only \`react\`, \`react/jsx-runtime\`, \`motion/react\` and files in its own folder.`,
  ]
  let group = ''
  let shown = ''
  const listed = new Set<string>()
  const add = (names: string[]) => {
    const fresh = names.filter((n) => !listed.has(n)).sort()
    fresh.forEach((n) => listed.add(n))
    return fresh
  }
  const lines = source.split('\n')
  for (const line of lines) {
    // A comment line starts a group; its first sentence is the heading.
    const heading = /^\/\/ ([^.]+)/.exec(line.trim())
    if (heading) {
      group = heading[1].trim()
      continue
    }
    const named = /^export (type )?\{([^}]+)\} from '([^']+)'/.exec(line.trim())
    const star = /^export \* from '([^']+)'/.exec(line.trim())
    let names: string[] = []
    let types = false
    if (named) {
      types = !!named[1]
      names = named[2].split(',').map((n) => n.trim().replace(/^type /, '')).filter(Boolean)
    } else if (star) {
      const mod = (await import(join(ROOT, 'src', 'vault-api', star[1]))) as Record<string, unknown>
      names = Object.keys(mod)
    } else continue
    const fresh = add(names)
    if (!fresh.length) continue
    if (group !== shown) out.push('', `## ${group}`, '')
    else out.push('')
    shown = group
    if (fresh.every((n) => components.has(n) || parts.has(n))) {
      out.push('Every built-in component, to compose in your own. Their props are in the `slidecraft-presentations` skill\'s `references/components.md`.', '')
      out.push(fresh.map((n) => `\`${n}\``).join(', '))
      continue
    }
    for (const n of fresh) {
      const kind = types ? 'type' : typeof api[n] === 'function' ? (/^use[A-Z]/.test(n) ? 'hook' : /^[A-Z]/.test(n) ? 'component or context' : 'function') : 'value'
      out.push(`- \`${n}\`: ${kind}`)
    }
  }
  return `${out.join('\n')}\n`
}

if (import.meta.main) {
  writeFileSync(CATALOGUE_FILE, buildCatalogue())
  console.log(`Wrote ${CATALOGUE_FILE}`)
  writeFileSync(API_FILE, await buildApiReference())
  console.log(`Wrote ${API_FILE}`)
}
