/**
 * How vault code reaches the app's modules (vault components plan, V1). A vault component is an
 * ES module with bare imports of the names below. In the browser an import map points each name
 * at a small shim module that re-exports the app's own instance from
 * `globalThis.__slidecraftModules`, so a vault component shares React, motion and the registry
 * with the app instead of loading copies.
 */

/** The bare imports vault code may use, and the shim file each maps to. */
export const VAULT_MODULES = {
  slidecraft: 'slidecraft.js',
  react: 'react.js',
  'react/jsx-runtime': 'react-jsx-runtime.js',
  'motion/react': 'motion-react.js',
} as const

export type VaultModuleName = keyof typeof VAULT_MODULES

export const VAULT_MODULE_NAMES = Object.keys(VAULT_MODULES) as VaultModuleName[]

/** Where the shims are served, below the app's base path. */
export const VAULT_RUNTIME_PREFIX = '/vault-runtime/'

/** The global the app fills before any vault module loads. */
export const VAULT_MODULES_GLOBAL = '__slidecraftModules'

export type VaultModules = Record<VaultModuleName, Record<string, unknown>>

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/
const SHIM_LOCAL = '__slidecraftModule__'

/** A shim module: `export const { a, b } = <the app's module>`, plus its default export. */
export function shimSource(name: VaultModuleName, exportNames: readonly string[]): string {
  // The module itself is held under a name no export can have (motion/react exports `m`).
  const names = [...new Set(exportNames)].filter((n) => n !== 'default' && n !== SHIM_LOCAL && IDENTIFIER.test(n)).sort()
  const lines = [
    `// Generated by Slidecraft: the app's own ${JSON.stringify(name)} for vault components.`,
    `const ${SHIM_LOCAL} = globalThis[${JSON.stringify(VAULT_MODULES_GLOBAL)}]?.[${JSON.stringify(name)}]`,
    `if (!${SHIM_LOCAL}) throw new Error(${JSON.stringify(`Slidecraft has not provided ${name} to vault components`)})`,
    `export default ${SHIM_LOCAL}.default ?? ${SHIM_LOCAL}`,
  ]
  if (names.length) lines.push(`export const { ${names.join(', ')} } = ${SHIM_LOCAL}`)
  return `${lines.join('\n')}\n`
}

/** The import map that sends each vault module name to its shim. */
export function vaultImportMap(base = ''): { imports: Record<string, string> } {
  const prefix = `${base.replace(/\/$/, '')}${VAULT_RUNTIME_PREFIX}`
  return { imports: Object.fromEntries(VAULT_MODULE_NAMES.map((n) => [n, prefix + VAULT_MODULES[n]])) }
}

/** The vault module served at a shim file name, if it is one. */
export function vaultModuleForFile(file: string): VaultModuleName | undefined {
  return VAULT_MODULE_NAMES.find((n) => VAULT_MODULES[n] === file)
}
