/**
 * Instructions for agents working in a vault (Part 4 §7.6, UX overhaul U4): a short generated
 * AGENTS.md that points at the slidecraft-presentations skill and lists the themes, plus the
 * component summary and templates the HTTP chat prompt still uses. A hand-written AGENTS.md is
 * never touched.
 */
import { existsSync, readFileSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { BUILTIN_SOURCE, getAllTemplates, getBuiltinComponent, getParts, getSourceProblems, getTopLevelComponents, sourceOfEntry, type RegistryConfig } from '../../src/components/slides/defineComponent.ts'
import { ensureServerComponents } from './serverRegistry.ts'
import '../../src/components/slides/index.ts'
import { getContentSources, getDefaultContentSource, type ContentSource } from './contentSources.ts'
import { VERSION } from './paths.ts'
import { executeTool } from './tools.ts'

export const GENERATED_PREFIX = '<!-- Generated by Slidecraft'
export const CONTENT_INSTRUCTIONS_FILE = 'AGENTS.md'

export const COMPONENT_CATEGORIES: Record<string, string[]> = {
  Structure: ['Presentation', 'Slide', 'Notes', 'Step'],
  Text: ['Title', 'Subtitle', 'Text', 'Accent', 'Highlight', 'Caption', 'Quote', 'CenteredStatement', 'TagPill', 'Section', 'Code', 'Punchline', 'LowerThird', 'Chapter'],
  Lists: ['List', 'ProConList'],
  Layout: ['TwoColumn', 'FourColumn', 'Stack', 'Divider', 'SplitBackground', 'ComparisonLayout', 'DefinitionLayout', 'PersonRow'],
  Content: ['Card', 'Callout', 'ContentBox', 'PersonCard', 'Legend', 'IconRow', 'PhaseRow', 'ComparisonTable'],
  'Data Visualization': ['Stat', 'ProgressBar', 'Spectrum', 'Timeline', 'Quadrants', 'ScatterChart', 'Gauge', 'GaugeRow', 'TraceTimeline', 'NumberPunch'],
  'Technical Diagrams': ['BlockDiagram', 'StackDiagram', 'CycleDiagram', 'PyramidDiagram', 'SequenceDiagram', 'ActivityDiagram', 'DataModel', 'FeedbackLoops', 'AppShellDiagram', 'BracketDiagram', 'SignalFlow', 'TracedPoints'],
  Media: ['ContentImage', 'Svg', 'BackgroundImage', 'YouTube', 'Annotate'],
}

/** Component list grouped by category, with every component's props; parts are listed with their parent. */
export function buildComponentSummary(): string {
  const all = getTopLevelComponents().map((c) => c.registry)
  const known = new Set(Object.values(COMPONENT_CATEGORIES).flat())
  const groups = { ...COMPONENT_CATEGORIES, Other: all.map((r) => r.name).filter((n) => !known.has(n)) }
  const withParts = (name: string) => {
    const parts = getParts(name).map((p) => p.registry.name)
    return parts.length ? `${name} (with ${parts.join(', ')})` : name
  }
  const lines = ['## Available components', '', '| Category | Components |', '|---|---|']
  for (const [category, names] of Object.entries(groups)) if (names.length) lines.push(`| ${category} | ${names.map(withParts).join(', ')} |`)
  lines.push('', '### Props', '')
  const propLine = (r: RegistryConfig) => {
    const props = r.props.map((p) => `\`${p.name}\`${p.default ? ` = ${p.default}` : ''}`).join(', ')
    return `**${r.name}**${r.parent ? ` (inside ${r.parent})` : ''} — ${r.description}${props ? ` Props: ${props}.` : ''}`
  }
  for (const r of all) {
    lines.push(`- ${propLine(r)}`)
    for (const part of getParts(r.name)) lines.push(`  - ${propLine(part.registry)}`)
  }
  return lines.join('\n')
}

/**
 * The vault's own components (vault components plan, V2), for the agent's standing instructions:
 * they are not in the skill's catalogue. Null when the vault has none.
 */
export async function buildVaultComponentSummary(vault: string): Promise<string | null> {
  await ensureServerComponents(vault)
  const own = getTopLevelComponents(vault).filter((c) => sourceOfEntry(c.registry) !== BUILTIN_SOURCE)
  const problems = getSourceProblems(vault)
  if (!own.length && !problems.length) return null
  const lines = ['## This vault\'s own components', '', 'Besides the built-ins in the skill\'s reference, decks in this vault can use these (their code is in `components/<Name>/`). Import them from `@components` like the others.', '']
  for (const { registry: r } of own) {
    const props = r.props.map((p) => `\`${p.name}\`${p.default ? ` = ${p.default}` : ''}`).join(', ')
    const parts = getParts(r.name, vault).map((p) => p.registry.name)
    lines.push(`- **${r.name}**${getBuiltinComponent(r.name) ? ' (replaces the built-in of that name in this vault)' : ''}: ${r.description}${props ? ` Props: ${props}.` : ''}${parts.length ? ` Parts: ${parts.join(', ')}.` : ''}`, `  \`${r.snippet.split('\n')[0]}\``)
  }
  for (const p of problems) lines.push(`- **${p.name}** is not available: ${p.message.split('\n')[0]}`)
  return lines.join('\n')
}

export function buildTemplateExamples(): string {
  const lines = ['## Slide templates', '', 'Starting points for whole slides:', '']
  for (const t of getAllTemplates()) lines.push(`### ${t.name}`, '', t.description, '', '```mdx', t.snippet, '```', '')
  return lines.join('\n')
}

export async function buildThemeSummary(): Promise<string> {
  const result = await executeTool('list_themes', {})
  const { themes, errors } = result.data as { themes: { id: string; name: string; description?: string; frames: string[]; source: string }[]; errors: Record<string, string[]> }
  const lines = ['## Themes', '', 'Set one on the deck root: `<Presentation theme="…">`.', '', '| Theme | From | Frames | Description |', '|---|---|---|---|']
  for (const t of themes) lines.push(`| \`${t.id}\` | ${t.source === 'builtin' ? 'built-in' : 'this folder'} | ${t.frames.length ? t.frames.map((f) => `\`${f}\``).join(', ') : '—'} | ${t.description ?? ''} |`)
  for (const [id, problems] of Object.entries(errors)) lines.push('', `Theme \`${id}\` has problems: ${problems.join('; ')}`)
  return lines.join('\n')
}

export async function buildFolderInstructions(port: number): Promise<string> {
  return [
    `${GENERATED_PREFIX} ${VERSION}. Slidecraft rewrites this file on start when it is out of date; replace it with your own AGENTS.md to keep house style here. -->`,
    '# Presentations in this vault',
    '',
    'This folder is a Slidecraft vault. Each subfolder holding an `index.mdx` is one presentation, named after its folder; its images sit beside it. Themes for this vault live in `themes/<id>/theme.json`.',
    '',
    'Before creating or changing a presentation, read `.claude/skills/slidecraft-presentations/SKILL.md` and follow it. Agents that load skills get it as the `slidecraft-presentations` skill. Its `references/` folder lists every component with its props.',
    '',
    `Inside Slidecraft the person sees the deck as you edit it. From a terminal, a deck is at http://localhost:${port}/v/<vault>/<name>.`,
    '',
    await buildThemeSummary(),
    '',
  ].join('\n')
}

export const isGenerated = (text: string): boolean => text.startsWith(GENERATED_PREFIX)

/** Folder instructions written by a person (never the generated file). */
export function readContentInstructions(dir = getDefaultContentSource().path): string | null {
  const file = join(dir, CONTENT_INSTRUCTIONS_FILE)
  if (!existsSync(file)) return null
  const text = readFileSync(file, 'utf8')
  return isGenerated(text) ? null : text
}

export type SyncResult = 'written' | 'unchanged' | 'hand-written' | 'read-only' | 'missing-dir'

/** Generate or refresh AGENTS.md in one vault (the default one when none is given). */
export async function syncFolderInstructions(port: number, source: ContentSource = getDefaultContentSource()): Promise<SyncResult> {
  if (source.readOnly) return 'read-only'
  if (!existsSync(source.path)) return 'missing-dir'
  const file = join(source.path, CONTENT_INSTRUCTIONS_FILE)
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (existing !== null && !isGenerated(existing)) return 'hand-written'
  const wanted = await buildFolderInstructions(port)
  if (existing === wanted) return 'unchanged'
  try {
    await writeFile(file, wanted)
    return 'written'
  } catch (error) {
    console.warn(`Could not write ${file}: ${(error as Error).message}`)
    return 'unchanged'
  }
}

/** Refresh AGENTS.md in every vault; a hand-written file is never touched. */
export async function syncAllFolderInstructions(port: number): Promise<Map<ContentSource, SyncResult>> {
  const results = new Map<ContentSource, SyncResult>()
  for (const source of getContentSources()) results.set(source, await syncFolderInstructions(port, source))
  return results
}
